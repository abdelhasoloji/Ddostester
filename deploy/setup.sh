#!/usr/bin/env bash
# WEDOS ShieldTest — idempotent provisioning/deploy on the server.
# Usage:
#   bash deploy/setup.sh                 # build + (re)start, allowlist unchanged
#   ALLOWED_TARGETS="127.0.0.1,host.test.internal" bash deploy/setup.sh
#
# This is the ONE-TIME provisioning script: it writes the systemd unit and the
# runtime secrets (/etc/ddostester.env). For automated redeploys (CI/CD) use
# deploy/update.sh instead, which only updates the code and never rewrites
# secrets or the service definition. See docs/ci-cd.md.
#
# Does NOT expose anything publicly: the API listens on 127.0.0.1 (access via
# SSH tunnel). Only adds a target if you pass it explicitly via env.
set -euo pipefail

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SERVICE="ddostester"
PORT="${PORT:-8080}"
HOST="${HOST:-127.0.0.1}"
ALLOWED_TARGETS="${ALLOWED_TARGETS:-127.0.0.1,localhost}"
# Persistence: if DATABASE_URL is set, the API uses PostgreSQL; otherwise it
# uses in-memory storage (lost on restart).
DATABASE_URL="${DATABASE_URL:-}"
# Auth (optional): if AUTH_JWT_SECRET is set, auth+RBAC is enabled.
AUTH_JWT_SECRET="${AUTH_JWT_SECRET:-}"
AUTH_USERS="${AUTH_USERS:-}"
# Class-C bench (optional): the app↔lab-runner bearer + governance label.
BENCH_RUNNER_TOKEN="${BENCH_RUNNER_TOKEN:-}"
LAB_TARGETS="${LAB_TARGETS:-}"
# Load agent (builtin by default; k6 delegates to the external tool).
AGENT="${AGENT:-builtin}"
RUN_USER="${SUDO_USER:-$(id -un)}"

echo "==> Directory: $REPO_DIR"
echo "==> Allowed targets (allowlist): $ALLOWED_TARGETS"

cd "$REPO_DIR"
echo "==> git pull"
git pull --ff-only || echo "   (pull skipped: local repo modified or offline)"

echo "==> npm install + build + test"
npm install
npm run build
npm test

echo "==> Writing secrets (EnvironmentFile, chmod 600)"
# Sensitive/complex values (JWT secret, users JSON, DB DSN) go into a protected
# environment file, not the systemd unit (world-readable). Lines are written
# only if the variable is provided.
ENVFILE="/etc/${SERVICE}.env"
sudo touch "$ENVFILE"
sudo chmod 600 "$ENVFILE"
# NOTE: use `if…fi`, not `[ -n "$X" ] && echo` — under `set -o pipefail` a
# trailing false test as the LAST command in the group makes the whole pipeline
# exit non-zero and `set -e` aborts before the systemd unit is written.
{
  echo "# Generated by deploy/setup.sh — runtime secrets (do not commit)."
  if [ -n "$DATABASE_URL" ]; then echo "DATABASE_URL=$DATABASE_URL"; fi
  if [ -n "$AUTH_JWT_SECRET" ]; then echo "AUTH_JWT_SECRET=$AUTH_JWT_SECRET"; fi
  if [ -n "$AUTH_USERS" ]; then echo "AUTH_USERS=$AUTH_USERS"; fi
  if [ -n "$BENCH_RUNNER_TOKEN" ]; then echo "BENCH_RUNNER_TOKEN=$BENCH_RUNNER_TOKEN"; fi
  if [ -n "$LAB_TARGETS" ]; then echo "LAB_TARGETS=$LAB_TARGETS"; fi
} | sudo tee "$ENVFILE" >/dev/null

echo "==> Writing the systemd service"
sudo tee "/etc/systemd/system/${SERVICE}.service" >/dev/null <<UNIT
[Unit]
Description=WEDOS ShieldTest control plane
After=network.target

[Service]
Type=simple
User=${RUN_USER}
WorkingDirectory=${REPO_DIR}/backend
Environment=PORT=${PORT}
Environment=HOST=${HOST}
Environment=ALLOWED_TARGETS=${ALLOWED_TARGETS}
Environment=AGENT=${AGENT}
EnvironmentFile=-${ENVFILE}
ExecStart=/usr/bin/node dist/server.js
Restart=on-failure

[Install]
WantedBy=multi-user.target
UNIT

echo "==> (re)starting the service"
sudo systemctl daemon-reload
sudo systemctl enable --now "${SERVICE}"
sudo systemctl restart "${SERVICE}"
sleep 1

echo "==> Loopback bind check (must be ONLY ${HOST}:${PORT})"
if command -v ss >/dev/null; then ss -tlnp 2>/dev/null | grep ":${PORT}" || true; fi

echo "==> Health check"
curl -fsS "http://${HOST}:${PORT}/health" && echo

cat <<MSG

✅ Deployed. The API + UI listen on http://${HOST}:${PORT} (loopback).
   Access from your machine (SSH tunnel, no public exposure):

     ssh -L ${PORT}:127.0.0.1:${PORT} ${RUN_USER}@<server-public-IP>

   then open http://localhost:${PORT} in your browser.
MSG
